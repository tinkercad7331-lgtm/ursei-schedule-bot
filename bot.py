def subjects_keyboard(group):
    rows = []
    for i, subj in enumerate(get_subjects(group)):
        mark = "✅ " if (group, subj) in homework else ""
        rows.append([InlineKeyboardButton(f"{mark}{subj}", callback_data=f"hws:{i}")])
    rows.append([InlineKeyboardButton("🏠 В меню", callback_data="menu")])
