user_groups = {}

def group_keyboard():
    return InlineKeyboardMarkup([
        [InlineKeyboardButton("РПД-101", callback_data="group:РПД-101"),
         InlineKeyboardButton("РПД-102", callback_data="group:РПД-102")],
        [InlineKeyboardButton("РПД-103", callback_data="group:РПД-103")]
    ])

def change_keyboard():
    return InlineKeyboardMarkup([[InlineKeyboardButton("🔄 Сменить группу", callback_data="change")]])

async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    user_groups.pop(update.effective_user.id, None)
    await update.message.reply_text("👋 Привет! Выбери свою группу:", reply_markup=group_keyboard())

async def choose_group(update: Update, context: ContextTypes.DEFAULT_TYPE):
    q = update.callback_query
    await q.answer()
    if q.data == "change":
        user_groups.pop(q.from_user.id, None)
        await q.edit_message_text("Выбери группу:", reply_markup=group_keyboard())
        return
    group = q.data.split(":", 1)[1]
    user_groups[q.from_user.id] = group
    await q.edit_message_text(
        f"✅ Группа выбрана: {group}\n\n📅 Введи число октября от 1 до 31.\nНапример: 15",
        reply_markup=change_keyboard()
    )

async def text_handler(update: Update, context: ContextTypes.DEFAULT_TYPE):
    uid = update.effective_user.id
    text = update.message.text.strip()

    if uid not in user_groups:
        await update.message.reply_text("Сначала выбери группу:", reply_markup=group_keyboard())
        return

    if not re.fullmatch(r"\d{1,2}", text):
        await update.message.reply_text("❌ Введи только число, например: 15")
        return

    day = int(text)
    key = f"{day:02d}"
    group = user_groups[uid]

    if key not in SCHEDULES[group]:
        await update.message.reply_text(
            f"📭 На {day} октября у группы {group} занятий нет или этой даты нет в расписании.",
            reply_markup=change_keyboard()
        )
        return

